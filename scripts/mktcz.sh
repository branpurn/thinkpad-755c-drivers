#!/bin/sh
# Package modules into Tiny Core-style .tcz extensions for tc32's tce-load.
#   scripts/mktcz.sh [name ...]   (default: modutils + every ext/*.ext)
# Output: out/tcz/<name>.tcz (+ .tcz.dep, .tcz.info, .tcz.list, .tcz.md5.txt)
# Layout inside each .tcz (TC convention):
#   usr/local/lib/modules/<kver>/kernel/...   (stripped .ko, uncompressed:
#                                              the squashfs is already xz)
#   usr/local/tce.installed/<name>            (run once by tce-load, as in
#                                              Tiny Core; tc32 >= PR #2)
. "$(dirname "$0")/common.sh"
KV=$(kver); MR="$OUT/modules/lib/modules/$KV"
[ -d "$MR/kernel" ] || die "no modules in $MR: run 'make kernel oot'"
command -v mksquashfs >/dev/null || die "mksquashfs missing (build it in $TC32_DIR: make tools)"
MODINFO=$(command -v modinfo || echo /sbin/modinfo)
T="$OUT/tcz"; mkdir -p "$T"; S="$BUILD/tcz-stage"

path_of() { # module name -> path relative to $MR
    n=$(echo "$1" | tr _ -)
    p=$(cd "$MR" && find kernel extra -name "$n.ko" 2>/dev/null | head -1)
    [ -n "$p" ] || p=$(cd "$MR" && find kernel extra -name "$(echo "$1" | tr - _).ko" | head -1)
    [ -n "$p" ] || die "module not built: $1"
    echo "$p"
}
ORDER=""
visit() { # depth-first: dependencies before dependents
    case " $ORDER " in *" $1 "*) return;; esac
    for d in $("$MODINFO" -F depends "$MR/$(path_of "$1")" | tr , ' '); do visit "$d"; done
    ORDER="$ORDER $1"
}

finish() { # name stagedir
    n=$1 d=$2
    find "$d" -exec touch -h -d "@$SOURCE_DATE_EPOCH" {} +
    rm -f "$T/$n.tcz"
    mksquashfs "$d" "$T/$n.tcz" -comp xz -noappend -all-root -quiet >/dev/null
    (cd "$d" && find . ! -type d | sed 's|^\./|/|' | sort) > "$T/$n.tcz.list"
    (cd "$T" && md5sum "$n.tcz" > "$n.tcz.md5.txt")
    log "$n.tcz: $(stat -c %s "$T/$n.tcz") bytes ($(du -sb "$d" | cut -f1) bytes unpacked)"
}

mk_modutils() {
    [ -x "$OUT/modutils/busybox" ] || die "run scripts/build-modutils.sh first"
    d="$S/modutils"; rm -rf "$d"; mkdir -p "$d/usr/local/bin" "$d/usr/local/sbin"
    cp "$OUT/modutils/busybox" "$d/usr/local/bin/busybox-modutils"
    for a in insmod rmmod lsmod modprobe depmod modinfo; do ln -s ../bin/busybox-modutils "$d/usr/local/sbin/$a"; done
    printf 'Title: modutils.tcz\nDescription: static busybox insmod/rmmod/lsmod/modprobe/depmod/modinfo for tc32\nKernel: %s\nLicense: GPL-2.0\n' "$KV" > "$T/modutils.tcz.info"
    : > "$T/modutils.tcz.dep"
    finish modutils "$d"
}

mk_ext() {
    n=$1; f="$TOP/ext/$n.ext"; [ -f "$f" ] || die "no such extension: $f"
    DESC="" MODS="" DEPS="" OPTIONAL=""
    . "$f"
    ORDER=""; for m in $MODS; do visit "$m"; done
    d="$S/$n"; rm -rf "$d"; mkdir -p "$d/usr/local/tce.installed"
    sh="$d/usr/local/tce.installed/$n"
    {
        echo '#!/bin/sh'
        echo "# $n.tcz: load modules in dependency order (generated by scripts/mktcz.sh)"
        echo "MD=/usr/local/lib/modules/$KV"
        echo 'PATH=/usr/local/sbin:/usr/local/bin:$PATH'
        echo 'rc=0'
        echo 'load() { # name file defaults'
        echo '    m=$(echo "$1" | tr - _); [ -d "/sys/module/$m" ] && return 0'
        echo '    a=$3; for c in $(cat /proc/cmdline); do case $c in "$m".*=*) a="$a ${c#$m.}";; esac; done'
        echo '    if insmod "$MD/$2" $a; then echo "  $m loaded${a:+ ($a)}"; else echo "  $m: insmod failed${a:+ ($a)}"; rc=1; fi'
        echo '}'
        for m in $ORDER; do
            v=ARGS_$(echo "$m" | tr - _); eval "args=\${$v:-}"
            echo "load $m $(path_of "$m") \"$args\""
        done
        if [ -n "$OPTIONAL" ]; then echo 'exit 0'; else echo 'exit $rc'; fi
    } > "$sh"
    chmod 755 "$sh"
    for m in $ORDER; do p=$(path_of "$m"); mkdir -p "$d/usr/local/lib/modules/$KV/$(dirname "$p")"; cp "$MR/$p" "$d/usr/local/lib/modules/$KV/$p"; done
    printf '%s\n' $DEPS > "$T/$n.tcz.dep"
    printf 'Title: %s.tcz\nDescription: %s\nKernel: %s\nModules (load order):%s\nLicense: GPL-2.0\n' "$n" "$DESC" "$KV" "$ORDER" > "$T/$n.tcz.info"
    finish "$n" "$d"
}

names=${*:-modutils $(cd "$TOP/ext" && ls *.ext | sed 's/\.ext$//')}
for n in $names; do
    case $n in modutils) mk_modutils ;; *) mk_ext "$n" ;; esac
done
